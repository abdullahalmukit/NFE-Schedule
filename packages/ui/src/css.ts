import { courseTone, COURSE_TONE_COUNT, type ThemeName } from "./theme";
import { tokens } from "./tokens";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function themeVars(theme: ThemeName, indent: string): string {
  const lines = Object.entries(tokens.color[theme]).map(
    ([k, v]) => `${indent}--nfe-${kebab(k)}: ${v};`,
  );
  // Cards: no shadow in dark mode, a faint one in light mode (DESIGN_SYSTEM §4).
  lines.push(
    `${indent}--nfe-card-shadow: ${theme === "dark" ? "none" : "0 1px 2px rgba(20, 50, 31, 0.06)"};`,
  );
  for (let i = 0; i < COURSE_TONE_COUNT; i++) {
    const t = courseTone(theme, i);
    lines.push(
      `${indent}--nfe-course-${i}-fill: ${t.fill};`,
      `${indent}--nfe-course-${i}-on-fill: ${t.onFill};`,
      `${indent}--nfe-course-${i}-tint: ${t.tint};`,
      `${indent}--nfe-course-${i}-on-tint: ${t.onTint};`,
    );
  }
  return lines.join("\n");
}

function fontStack(variable: string, family: string): string {
  return `var(${variable}), "${family}", var(--nfe-font-bangla), "${tokens.font.bangla}", ui-sans-serif, system-ui, sans-serif`;
}

/**
 * Tailwind v4 theme for the web app, generated from `design/tokens.json`.
 * Colours are CSS variables, so `data-theme="dark" | "light"` on any element
 * switches the theme below it; without the attribute the system decides.
 * Course colours: `var(--nfe-course-<i>-fill | -on-fill | -tint | -on-tint)`.
 */
export function buildThemeCss(): string {
  const colorKeys = Object.keys(tokens.color.dark);
  const sizes = Object.entries(tokens.size);
  const radii = Object.entries(tokens.radius).filter(([k]) => k !== "pill");
  return [
    "/* Generated by packages/ui/scripts/build-theme-css.ts from design/tokens.json. Do not edit. */",
    "",
    "@theme inline {",
    ...colorKeys.map((k) => `  --color-${kebab(k)}: var(--nfe-${kebab(k)});`),
    ...Object.entries(tokens.brand).map(([k, v]) => `  --color-${kebab(k)}: ${v};`),
    "",
    `  --font-display: ${fontStack("--nfe-font-display", tokens.font.display)};`,
    `  --font-body: ${fontStack("--nfe-font-body", tokens.font.body)};`,
    "",
    ...sizes.flatMap(([k, v]) => [
      `  --text-${k}: ${v}px;`,
      `  --text-${k}--line-height: ${v >= 24 ? "1.2" : "1.45"};`,
    ]),
    "",
    ...radii.map(([k, v]) => `  --radius-${k}: ${v}px;`),
    "",
    "  --shadow-card: var(--nfe-card-shadow);",
    "}",
    "",
    ":root,",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    themeVars("dark", "  "),
    "}",
    "",
    '[data-theme="light"] {',
    "  color-scheme: light;",
    themeVars("light", "  "),
    "}",
    "",
    "@media (prefers-color-scheme: light) {",
    "  :root:not([data-theme]) {",
    "    color-scheme: light;",
    themeVars("light", "    "),
    "  }",
    "}",
    "",
    "/* Bangla text: line height +10 % (DESIGN_SYSTEM.md §3). */",
    ":lang(bn) {",
    "  line-height: 1.6;",
    "}",
    "",
  ].join("\n");
}
